"""Exhaustively compare scaled SV bindings and output to an independent fixture oracle."""
import argparse
from contextlib import closing
import hashlib
import json
from pathlib import Path
import re
import sys
import time

ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from clocktree.sv_templates import SVPlan,database
from clocktree.storage import write_graph
from check_sv_templates import TEMPLATES


def expected(index):
    mux=index%2==0
    values=dict(var_rst='sv_top.rst_n' if mux else 'sv_top.rst_alt_n',
                var_clkip='sv_top.cd' if mux else 'sv_top.ng3',
                var_div='sv_top.D[9:6]' if mux else 'sv_top.C[3:0]',
                var_swdone='sv_top.E[10]' if mux else 'sv_top.E[11]',
                var_gt0='sv_top.C[7]' if mux else 'sv_top.C[6]',
                var_gt1="1'b1" if mux else 'sv_top.C[5]',
                var_gt2="1'b1" if mux else 'sv_top.C[4]',
                var_pll0='sv_top.a',var_pll1='sv_top.b' if mux else "1'b1",
                var_pll2="1'b1",var_pll3="1'b1")
    if mux:values['var_pllsel']='sv_top.D[5:2]'
    return values


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,required=True)
    parser.add_argument('--out',type=Path,required=True)
    parser.add_argument('--terminals',type=int,required=True)
    args=parser.parse_args();out=args.out.resolve();out.mkdir(parents=True,exist_ok=True)
    plan=SVPlan(args.source/'plan/plan.sqlite');start=time.monotonic()
    # Compare every partial-report row, including all candidates of each skipped branch.
    partial=json.loads((args.source/'scale.sv.mapping.json').read_text(encoding='utf-8'))
    assert partial['terminal_count']==args.terminals
    seen=set();selections={}
    for row in partial['branches']:
        index=int(row['instance'].rsplit('_',1)[1]);assert index not in seen;seen.add(index)
        want=expected(index)
        if index%2:
            assert not row['ready'] and row['issues']
            candidates=row['available_choices']['var_swdone']
            assert {c['expression'] for c in candidates}=={'sv_top.E[11]','sv_top.E[12]'}
            chosen=next(c for c in candidates if c['expression']=='sv_top.E[11]')
            selections[row['id']]={'var_swdone':chosen['id']};want.pop('var_swdone')
        else:assert row['ready'] and not row['issues']
        assert row['values']==want,(index,row['values'],want)
    assert seen==set(range(args.terminals));del partial
    output=out/'all-selected.sv';export_start=time.monotonic()
    result=plan.export(TEMPLATES,output,selections)
    export_seconds=time.monotonic()-export_start
    assert (result['terminals'],result['blocks'],result['skipped'])==(args.terminals,args.terminals,0)
    # This oracle uses literal replacement, separate from the product renderer.
    with output.open(encoding='utf-8') as generated,closing(database(plan.path)) as db:
        assert generated.readline().startswith('// Generated by ClockTree7')
        assert generated.readline().startswith('// DFT zero assumptions:')
        offset=0
        while offset<args.terminals:
            total,rows=plan.branches(offset=offset,_db=db)
            for branch in rows:
                index=int(branch['instance'].rsplit('_',1)[1]);want=expected(index)
                value=plan.resolve(branch,TEMPLATES,selections.get(branch['id']),_db=db)
                assert value['ready'] and value['values']==want,(index,value)
                assert value['reset']['basis']=='branch_origin'
                assert value['reset']['layer']==(1 if index%2==0 else 2)
                text=TEMPLATES['with_mux' if index%2==0 else 'without_mux']
                for key,replacement in want.items():text=text.replace('$'+key,replacement)
                block='\n// CT7 branch {} | {}.{} | {}\n{}\n'.format(branch['id'],branch['instance'],branch['pin'],want['var_clkip'],text)
                assert generated.read(len(block))==block,'Incorrect emitted block '+str(index)
            offset+=len(rows)
        assert generated.read()==''
    before=hashlib.sha256(output.read_bytes()).hexdigest()
    again=plan.export(TEMPLATES,output,selections)
    assert again['blocks']==args.terminals and again['skipped']==0
    assert hashlib.sha256(output.read_bytes()).hexdigest()==before
    final=json.loads(output.with_name(output.name+'.mapping.json').read_text(encoding='utf-8'))
    assert len(final['branches'])==args.terminals and all(r['ready'] for r in final['branches'])
    assert len({r['id'] for r in final['branches']})==args.terminals
    write_graph(out/'acceptance.json',dict(passed=True,synthetic_terminal_expansion=True,
        terminal_inputs=args.terminals,partial_exact_bindings=args.terminals,
        candidate_lists_checked=args.terminals//2,final_exact_blocks=args.terminals,
        every_origin_reset_checked=True,repeat_export_sha256=before,
        export_seconds=export_seconds,total_seconds=time.monotonic()-start))
    print('SV_EXHAUSTIVE_ORACLE_ACCEPTED '+str(args.terminals),flush=True)


if __name__=='__main__':main()
